// sync-gui-dna.mjs — writes VectFox's copies of the GUI-DNA from mvu-helper's.
//
//   node tools/sync-gui-dna.mjs
//
// mvu-helper owns the GUI-DNA (its devdoc/gui-dna.md): every adopter uses its gui-dna.css word for word with the class
// prefix swapped. VectFox also takes its palette.css, so it has no colours of its own, and its gene builders. This reads
// the sibling mvu-helper repo and writes src/shared/gui-dna/ with `mvuh-` replaced by `vfx-`, each under a header saying
// so. A change to any of them is made in mvu-helper and synced here; tests/gui-dna-sync.test.js fails when a copy differs
// from what this writes.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_FOLDER = join(repoRoot, '..', 'mvu-helper', 'src', 'features', 'settings-panel');
const COPY_FOLDER = join(repoRoot, 'src', 'shared', 'gui-dna');
const SOURCE_PREFIX = 'mvuh-';
const VECTFOX_PREFIX = 'vfx-';

// mvu-helper keeps its builders in a feature, and VectFox in src/shared/gui-dna/, one folder below the escaper.
const SOURCE_ESCAPER_PATH = "'../../shared/html-escape.js'";
const VECTFOX_ESCAPER_PATH = "'../html-escape.js'";

const headerOf = (name, open, close, lineStart) => `${open} GENERATED by tools/sync-gui-dna.mjs from mvu-helper/src/features/settings-panel/${name}, with the\n`
    + `${lineStart} \`mvuh-\` prefix swapped for \`vfx-\`. Do not edit it here: change it in mvu-helper, then run the sync again.\n`
    + `${lineStart} The notes below are the source's own.${close}\n\n`;

const CSS_HEADER = { open: '/*', close: ' */', lineStart: ' *' };
const JS_HEADER = { open: '//', close: '', lineStart: '//' };

// Each synced file: its name in both folders, and its comment style.
export const SYNCED_FILES = [
    { name: 'gui-dna.css', header: CSS_HEADER },
    { name: 'palette.css', header: CSS_HEADER },
    { name: 'gui-dna-core.js', header: JS_HEADER },
].map(file => ({ ...file, source: join(SOURCE_FOLDER, file.name), copy: join(COPY_FOLDER, file.name) }));

/** One synced file's copy text: its header, then the source with every `mvuh-` swapped, line endings as LF. */
export function syncedCopyText(file, sourceText) {
    const { open, close, lineStart } = file.header;
    return headerOf(file.name, open, close, lineStart)
        + sourceText.replace(/\r\n/g, '\n').split(SOURCE_PREFIX).join(VECTFOX_PREFIX).split(SOURCE_ESCAPER_PATH).join(VECTFOX_ESCAPER_PATH);
}

function main() {
    const missing = SYNCED_FILES.find(file => !existsSync(file.source));
    if (missing) {
        console.error(`sync-gui-dna: mvu-helper not found at ${missing.source}. Clone it beside this repo first.`);
        process.exit(1);
    }
    for (const file of SYNCED_FILES) {
        writeFileSync(file.copy, syncedCopyText(file, readFileSync(file.source, 'utf8')));
        console.log(`sync-gui-dna: wrote ${file.copy}`);
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
